// Phase 2, step 2: build exam-tags.json (every printed tag -> canonical exams) for review.
// Usage: node tools/build-exam-tags.mjs   (after parse-new.mjs)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { parseTag, examKey, examName, examType, OLD_EXAMS } from './exams.mjs';

const recs = JSON.parse(readFileSync('tools/out/new-records.json', 'utf8'));
// the original 956 records (merge.mjs saves a copy before it rewrites by-subject/questions.json)
const ORIG = existsSync('tools/out/questions.orig.json') ? 'tools/out/questions.orig.json' : 'by-subject/questions.json';
const old = JSON.parse(readFileSync(ORIG, 'utf8'));

const aliases = {};
const exams = {};
const note = (e, src) => {
  const k = examKey(e);
  exams[k] ??= { key: k, name: examName(e), type: examType(e), org: e.org, post: e.post ?? null, year: e.year ?? null, printed_as: new Set(), records: 0 };
  if (!exams[k].year && e.year) { exams[k].year = e.year; exams[k].name = examName(e); }
  exams[k].printed_as.add(src);
  exams[k].records++;
  return k;
};
for (const r of recs) for (const t of r.raw_tags) aliases[t] = parseTag(t).map((e) => note(e, t));
for (const r of old) {
  const m = OLD_EXAMS[r.exam];
  if (Array.isArray(m)) aliases[r.exam] = m.map((e) => note(e, r.exam));
  else if (m === 'by-date') {
    const e = r.exam.startsWith('BPSC') ? { org: 'BPSC', post: 'AP', year: +r.date.slice(0, 4) } : { org: 'BSCL', post: 'AE(CSE)', year: +r.date.slice(0, 4) };
    (aliases[r.exam] ??= []).includes(examKey(e)) || aliases[r.exam].push(note(e, r.exam));
    if (aliases[r.exam].includes(examKey(e))) exams[examKey(e)].records++;
  }
}

const list = Object.values(exams).map((e) => ({ ...e, printed_as: [...e.printed_as].sort() }))
  .sort((a, b) => a.org.localeCompare(b.org) || String(a.post).localeCompare(String(b.post)) || (a.year ?? 0) - (b.year ?? 0));
writeFileSync('exam-tags.json', JSON.stringify({ note: 'Generated by tools/build-exam-tags.mjs. aliases: printed tag or old exam name -> canonical exam keys. Fix wrong merges in tools/exams.mjs (TAG_FIX, ORG, OLD_EXAMS) and re-run.', exams: list, aliases }, null, 1));

// review table
const lines = list.map((e) => `${String(e.records).padStart(3)}  ${e.type.padEnd(11)} ${e.name.padEnd(42)}  <= ${e.printed_as.slice(0, 4).join(' | ')}${e.printed_as.length > 4 ? ' | …' : ''}`);
writeFileSync('tools/out/exam-review.txt', lines.join('\n'));
console.log('canonical exams', list.length, 'aliases', Object.keys(aliases).length);

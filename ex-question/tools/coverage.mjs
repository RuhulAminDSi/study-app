// Exam Edge coverage board (plan C0.1): PYQ load per lesson for chapters 2, 4, 7, 9, 10, 11, 15-19.
// Reads by-subject/frequency.json, exam-tags.json, lesson-map.json, server/data/notes/manifest.json,
// server/data/questions/<CODE>.json and server/data/exam-kits/<slug>.json (when kits exist).
// Output: COVERAGE.md. Usage: node tools/coverage.mjs   (run from ex-question/)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const SERVER = join(ROOT, '..', 'server', 'data');
const json = (p) => JSON.parse(readFileSync(p, 'utf8'));

const freq = json(join(ROOT, 'by-subject/frequency.json'));
const tags = json(join(ROOT, 'exam-tags.json'));
const { map, _newLessons: newLessons } = json(join(ROOT, 'lesson-map.json'));
const manifest = json(join(SERVER, 'notes/manifest.json')).notes;

const SUBJECTS = { ICS: 2, DLD: 4, CA: 7, NET: 9, SPL: 10, OOP: 11, DSA: 15, DBMS: 16, SE: 17, OS: 18, AI: 19 };
const yearOf = Object.fromEntries(tags.exams.map((e) => [e.name, e.year]));

// lessons per chapter: the replace-mode note sets (one per seed lesson), then the planned revision lessons
const lessons = [];
for (const [subject, chapter] of Object.entries(SUBJECTS)) {
  for (const n of manifest.filter((x) => x.chapterNumber === chapter && x.mode === 'replace' && !x.slug.startsWith('pyq-'))) {
    lessons.push({ slug: n.slug, subject, chapter, title: n.lessonTitleEn, isNew: false });
  }
  for (const [slug, l] of Object.entries(newLessons)) if (l.chapter === chapter) lessons.push({ slug, subject, chapter, title: l.title, isNew: true });
}
const bySlug = Object.fromEntries(lessons.map((l) => [l.slug, { ...l, groups: [], clusters: {} }]));

const unmapped = {};
for (const g of freq) {
  if (!(g.subject in SUBJECTS)) continue;
  const slug = map[g.group] ?? map[`${g.subject}::${g.cluster}`];
  if (!slug || !bySlug[slug]) { unmapped[g.subject] ??= {}; unmapped[g.subject][g.cluster] = (unmapped[g.subject][g.cluster] ?? 0) + 1; continue; }
  const L = bySlug[slug];
  L.groups.push(g);
  L.clusters[g.cluster] = (L.clusters[g.cluster] ?? 0) + g.asked_count;
}

// starter bank: questions whose topic is the seed lesson title
const bankCount = {};
for (const subject of Object.keys(SUBJECTS)) {
  const file = join(SERVER, 'questions', `${subject}.json`);
  if (!existsSync(file)) continue;
  const raw = json(file);
  for (const q of Array.isArray(raw) ? raw : raw.questions) {
    const key = q.lesson_slug ?? lessons.find((l) => l.subject === subject && l.title === q.topic)?.slug;
    if (!key) continue;
    bankCount[key] ??= { mcq: 0, written: 0, programming: 0 };
    bankCount[key][q.type] = (bankCount[key][q.type] ?? 0) + 1;
  }
}

const rows = [];
for (const L of Object.values(bySlug)) {
  const asked = L.groups.reduce((s, g) => s + g.asked_count, 0);
  const recent = L.groups.reduce((s, g) => s + g.asked_in.filter((n) => (yearOf[n] ?? 0) >= 2023).length, 0);
  const hot = L.groups.filter((g) => g.asked_count >= 3).length;
  const repeats = L.groups.filter((g) => g.asked_count >= 2).length;
  const b = bankCount[L.slug] ?? { mcq: 0, written: 0, programming: 0 };
  const kit = existsSync(join(SERVER, 'exam-kits', `${L.slug}.json`));
  const top = Object.entries(L.clusters).sort((a, c) => c[1] - a[1]).slice(0, 3).map(([k, v]) => `${k} (${v})`).join('; ');
  rows.push({ ...L, asked, recent, hot, repeats, distinct: L.groups.length, b, kit, top });
}

const out = [
  '# Exam Edge coverage board',
  '',
  'Generated by `node tools/coverage.mjs` from `by-subject/frequency.json` and `lesson-map.json`. Plan:',
  '`docs/superpowers/plans/2026-10-16-exam-edge-lesson-upgrade.md`. *Asked* = exam appearances (viva and suggestions',
  'excluded); *2023+* = appearances in exams from 2023 on; *Repeats* = questions asked in 2 or more exams.',
  'Bank targets per lesson (spec §5.1): MCQ ≥30, written ≥10, programming/SQL/numerical ≥3.',
  '',
];
for (const [subject, chapter] of Object.entries(SUBJECTS)) {
  const rs = rows.filter((r) => r.subject === subject).sort((a, c) => c.asked - a.asked);
  out.push(`## Chapter ${chapter} · ${subject}`, '');
  out.push('| Lesson | Distinct Qs | Asked | 2023+ | Repeats | Top clusters | Bank MCQ / written / prog | Kit |', '|---|---|---|---|---|---|---|---|');
  for (const r of rs) {
    out.push(`| \`${r.slug}\`${r.isNew ? ' *(new)*' : ''} | ${r.distinct} | ${r.asked} | ${r.recent} | ${r.repeats} | ${r.top || '—'} | ${r.b.mcq} / ${r.b.written} / ${r.b.programming} | ${r.kit ? '✓' : '—'} |`);
  }
  const u = unmapped[subject];
  if (u) out.push('', `Unmapped clusters: ${Object.entries(u).sort((a, c) => c[1] - a[1]).map(([k, v]) => `${k} (${v})`).join('; ')}`);
  out.push('');
}
writeFileSync(join(ROOT, 'COVERAGE.md'), out.join('\n'));

const realUnmapped = Object.entries(unmapped).flatMap(([s, c]) => Object.keys(c).filter((k) => k !== 'Other').map((k) => `${s}::${k}`));
console.log(`lessons ${rows.length} | kits ${rows.filter((r) => r.kit).length} | unmapped non-Other clusters ${realUnmapped.length}`);
if (realUnmapped.length) console.log('  ' + realUnmapped.join('\n  '));
